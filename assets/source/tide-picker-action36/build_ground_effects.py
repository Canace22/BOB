"""Extract reviewed source ground rings as independent world-space atlases.

Does not modify animations.json: merge only after body/FX review. Source rings
can retain occlusion gaps where the original character stood; no missing
pixels are invented. Body frames are never generated by this script.
"""
import json, sys, hashlib
import numpy as np
from scipy import ndimage as ndi
from PIL import Image,ImageDraw
from build import BASE,RUNTIME,REVIEW,PIVOT,CANVAS,read_frame,register_rgba,atlas

CONFIG={'heavy':{'band':295,'start':8}, 'dive':{'band':350,'start':11}}

def extract(rgb,key):
    p=rgb.astype(float);yy=np.indices(rgb.shape[:2])[0]
    cyan=np.minimum(p[:,:,1]-p[:,:,0]-10,p[:,:,2]-p[:,:,0]-5)
    alpha=np.clip(cyan/38,0,1)*np.clip((p[:,:,1]-85)/50,0,1)
    alpha[yy<CONFIG[key]['band']]=0
    labels,n=ndi.label(alpha>.025)
    sizes=np.bincount(labels.ravel());sizes[0]=0
    # Keep only components connected to the reviewed ground band; cyan cape
    # highlights above the ring are not an effect layer.
    seed_y=330 if key=='heavy' else 350
    ground_labels=np.unique(labels[(yy>=seed_y)&(alpha>.025)])
    ground_labels=ground_labels[ground_labels!=0]
    alpha*=(sizes[labels]>80)&np.isin(labels,ground_labels)
    p[alpha==0]=0
    return Image.fromarray(np.dstack([p,alpha*255]).clip(0,255).astype('uint8'))

def build(key,source):
    cfg=CONFIG[key];times=source['source_seconds'];frames=[]
    root=np.array(source['root_source']);scale=source['scale']
    matrix=np.array([[scale,0,PIVOT[0]-root[0]*scale],[0,scale,PIVOT[1]-root[1]*scale]])
    for i,second in enumerate(times):
        image=extract(read_frame(source['source'],second),key) if i>=cfg['start'] else Image.new('RGBA',(768,432))
        frames.append(Image.fromarray(register_rgba(image,matrix)))
    meta=atlas(frames,key,'ground-fx',PIVOT)
    meta.update(frame_count=len(frames),event_frame=cfg['start'],space='world',blend='normal',source_kind='video-extracted ground response',source=source['source'],source_sha256=source['source_sha256'])
    sheet=Image.new('RGB',(4*320,((len(frames)+3)//4)*240),'#132b36')
    for i,image in enumerate(frames):
        tile=Image.new('RGBA',(CANVAS,CANVAS),'#132b36');tile.alpha_composite(image)
        tile=tile.crop((160,300,480,540))
        sheet.paste(tile.convert('RGB'),(i%4*320,i//4*240))
        ImageDraw.Draw(sheet).text((i%4*320+8,i//4*240+8),f'{key} {i}',fill='white')
    sheet.save(REVIEW/f'{key}-world-ring-review.jpg',quality=95)
    return {'fx':meta,'fx_blend':'normal','fx_source':{'path':source['source'],'sha256':source['source_sha256'],'seconds':times,'method':'source cyan ground response, reviewed source-coordinate band, component speckle removal, fixed ground root and scale','known_limits':['Source ring contains small occlusion gaps at original feet; displayed behind clean replacement body.'],'status':'candidate_pending_source_and_world_space_review'}}

if __name__=='__main__':
    source=json.loads((RUNTIME/'animations.json').read_text(encoding='utf-8'))['actions']
    path=BASE/'ground-effects.json';data=json.loads(path.read_text(encoding='utf-8')) if path.exists() else {'actions':{}}
    for key in sys.argv[1:]:
        data['actions'][key]=build(key,source[key]);print('Ground FX',key,flush=True)
    path.write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8',newline='\n')
